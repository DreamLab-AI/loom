#!/usr/bin/env python3
"""Compare the 2026-09-21 re-run of rescore.py against RESCORE.md and the paper.

RESCORE.md is a prose report of the original (lost) machine output, so the only
way to check the re-run against it is to parse its markdown table back into
numbers and diff every cell. This does that, plus the four figures the paper
itself quotes, and writes RESCORE-2026-09-21.md.
"""
from __future__ import annotations
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "rescore_results.json")
MD = os.path.join(HERE, "RESCORE.md")
OUT = os.path.join(HERE, "RESCORE-2026-09-21.md")
THRESHOLDS = ["0.80", "0.85", "0.90"]
# rescore.py keys its per-threshold dict with str(float), i.e. "0.8"/"0.85"/"0.9".
JKEY = {"0.80": "0.8", "0.85": "0.85", "0.90": "0.9"}

# Figures the PAPER (docs/research/paper-v8/main.tex, sec:rescore) states.
PAPER = {
    "ceiling@0.80": 0.980,
    "ceiling@0.85": 0.968,
    "ceiling_lexical": 0.964,
    "n_negative_ci_excluding_zero": 30,
    "pooled_n01@0.85": 3,
    "pooled_items": 11360,
    "max_single_model_n01_any_threshold": 4,
    "qwen_lexical_gain": -0.050,
    "qwen_gain@0.80": -0.034,
    "threshold_0.90_below_lexical": True,
}

_NUM = re.compile(r"[−-]?\.?\d*\.?\d+")


def num(tok: str):
    tok = tok.replace("−", "-").replace("**", "").strip()
    m = re.match(r"^(-?)(\.\d+|\d+\.\d+|\d+)$", tok)
    if not m:
        return None
    return float(m.group(0))


def parse_md_table(path: str):
    """Parse the side-by-side table of RESCORE.md into
    {model: {'lex': (R,C,G), '0.80': (R,C,G,lo,hi), ...}}."""
    rows = {}
    for line in open(path, encoding="utf-8"):
        if not line.startswith("| ") or line.startswith("|---") or "lexical R/C/G" in line:
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) != 5:
            continue
        model = cells[0]
        if model in ("model", "**exposed**", "**unexposed**"):
            continue
        entry = {}
        lex = [num(x) for x in cells[1].split("/")]
        if any(v is None for v in lex):
            continue
        entry["lex"] = tuple(lex)
        ok = True
        for t, cell in zip(THRESHOLDS, cells[2:5]):
            body, _, ci = cell.partition("[")
            rcg = [num(x) for x in body.strip().split("/")]
            ci_v = [num(x) for x in ci.rstrip("] ").split(",")] if ci else [None, None]
            if any(v is None for v in rcg):
                ok = False
                break
            entry[t] = tuple(rcg) + tuple(ci_v)
        if ok:
            rows[model] = entry
    return rows


def fmt(v, width=6):
    return f"{v:+.3f}" if isinstance(v, float) else str(v)


def main() -> int:
    if not os.path.exists(RES):
        sys.exit("rescore_results.json missing - run rescore.py first")
    res = json.load(open(RES))
    md = parse_md_table(MD)
    pm = res["per_model"]

    lines = []
    A = lines.append
    A("# Semantic re-score — re-run of 2026-09-21, compared to RESCORE.md and the paper")
    A("")
    A("`rescore.py` was released without `embed_lib.py`, `copy_contexts.json`, "
      "`rescore_results.json` or `embed_cache.json`, so it could not be run as "
      "released (R5-numbers.md §4.3). `embed_lib.py` has been reimplemented from "
      "`rescore.py`'s calling conventions and RESCORE.md's method description, and "
      "`copy_contexts.json` regenerated by `make_copy_contexts.py` with the frozen "
      "v1 scaffold engine under a hard gate (every question's recomputed exposed-gold "
      "count equals the stored `n_gold_exposed`; mean lexical ceiling 0.964477). "
      "`rescore.py` itself was then run **unmodified**.")
    A("")
    A("Two independent checks say the reconstruction is faithful rather than merely "
      "plausible: the gold-title count is **778**, exactly the figure RESCORE.md "
      "records, and the total unique candidate-string count is within a few percent "
      "of RESCORE.md's 274,616 — both are emergent properties of `extract_candidates`, "
      "which was reconstructed from prose.")
    A("")

    # ---- headline table -------------------------------------------------
    A("## Per-model comparison (re-run vs RESCORE.md)")
    A("")
    A("Each cell is `re-run` / `RESCORE.md` / Δ. R = recall, C = ceiling, G = gain.")
    A("")
    A("| model | metric | lexical | sem@0.80 | sem@0.85 | sem@0.90 |")
    A("|---|---|---|---|---|---|")
    deviations = []
    for label, m in pm.items():
        disp = m["display"]
        old = md.get(disp)
        for metric, key, oi in (("R", "semantic_recall", 0),
                                ("C", "semantic_ceiling", 1),
                                ("G", "semantic_gain", 2)):
            lexkey = {"R": "lexical_recall", "C": "lexical_ceiling", "G": "lexical_gain"}[metric]
            cells = []
            lv = m[lexkey]
            ov = old["lex"][oi] if old else None
            d = None if ov is None else round(lv - ov, 4)
            cells.append(f"{lv:.3f} / {ov if ov is None else f'{ov:.3f}'} / "
                         f"{'—' if d is None else f'{d:+.3f}'}")
            if d is not None and abs(d) > 0.0006:
                deviations.append((disp, f"lexical {metric}", lv, ov, d))
            for t in THRESHOLDS:
                nv = m["semantic"][JKEY[t]][key]
                ovt = old[t][oi] if old else None
                dt = None if ovt is None else round(nv - ovt, 4)
                cells.append(f"{nv:.3f} / {ovt if ovt is None else f'{ovt:.3f}'} / "
                             f"{'—' if dt is None else f'{dt:+.3f}'}")
                if dt is not None and abs(dt) > 0.0006:
                    deviations.append((disp, f"sem@{t} {metric}", nv, ovt, dt))
            A(f"| {disp} | {metric} | " + " | ".join(cells) + " |")
    A("")

    # ---- paper-level checks ---------------------------------------------
    ceils = {t: sorted({round(pm[l]["semantic"][JKEY[t]]["semantic_ceiling"], 4) for l in pm})
             for t in THRESHOLDS}
    lex_ceils = sorted({round(pm[l]["lexical_ceiling"], 4) for l in pm})
    n_neg = sum(1 for l in pm for t in THRESHOLDS
                if pm[l]["semantic"][JKEY[t]]["gain_ci95"][1] < 0)
    n_tot = len(pm) * len(THRESHOLDS)
    pooled = res["pooled_n01_at_0.85"]
    max_n01 = max(pm[l]["semantic"][JKEY[t]]["n01_unexposed_recovered"]
                  for l in pm for t in THRESHOLDS)
    qw = pm["qwen-2.5-72b"]

    A("## The four figures the paper itself states")
    A("")
    A("| paper claim | paper value | re-run value | verdict |")
    A("|---|---|---|---|")

    def row(claim, pv, nv, ok):
        A(f"| {claim} | {pv} | {nv} | {'REPLICATES' if ok else '**DEVIATES**'} |")

    c80 = ceils["0.80"][0] if len(ceils["0.80"]) == 1 else ceils["0.80"]
    c85 = ceils["0.85"][0] if len(ceils["0.85"]) == 1 else ceils["0.85"]
    lexc = lex_ceils[0] if len(lex_ceils) == 1 else lex_ceils
    row("semantic ceiling at 0.80", "0.980", f"{c80}", abs(float(c80) - 0.980) < 0.0006)
    row("semantic ceiling at 0.85", "0.968", f"{c85}", abs(float(c85) - 0.968) < 0.0006)
    row("lexical ceiling", "0.964", f"{lexc}", abs(float(lexc) - 0.9645) < 0.001)
    row("all model×threshold gains negative, CI excludes zero", "30 of 30",
        f"{n_neg} of {n_tot}", n_neg == n_tot == 30)
    row("pooled beyond-exposure recovery at 0.85", "3 of 11,360",
        f"{pooled['n01']} of {pooled['n_items']:,}",
        pooled["n01"] == 3 and pooled["n_items"] == 11360)
    row("largest single-model n01 at any threshold", "4", f"{max_n01}", max_n01 == 4)
    row("Qwen-2.5-72B gain, lexical → sem@0.80", "−0.050 → −0.034",
        f"{qw['lexical_gain']:+.3f} → {qw['semantic']['0.8']['semantic_gain']:+.3f}",
        abs(qw["lexical_gain"] + 0.050) < 0.0006
        and abs(qw["semantic"]["0.8"]["semantic_gain"] + 0.034) < 0.0006)
    below = all(pm[l]["semantic"]["0.9"]["semantic_recall"] < pm[l]["lexical_recall"]
                and pm[l]["semantic"]["0.9"]["semantic_ceiling"] < pm[l]["lexical_ceiling"]
                for l in pm)
    row("at 0.90 both recall and ceiling fall below lexical", "yes",
        "yes" if below else "no", below)
    A("")

    # ---- n01 table -------------------------------------------------------
    A("## Beyond-exposure recovery (n01), all thresholds")
    A("")
    A("| model | n01@0.80 | n01@0.85 | n01@0.90 |")
    A("|---|---:|---:|---:|")
    for label, m in pm.items():
        A(f"| {m['display']} | " + " | ".join(
            str(m["semantic"][JKEY[t]]["n01_unexposed_recovered"]) for t in THRESHOLDS) + " |")
    tot = {t: sum(pm[l]["semantic"][JKEY[t]]["n01_unexposed_recovered"] for l in pm)
           for t in THRESHOLDS}
    A(f"| **pooled** | {tot['0.80']} | {tot['0.85']} | {tot['0.90']} |")
    A("")
    A(f"Pooled 2×2 at 0.85: n11={pooled['n11']:,}, n10={pooled['n10']:,}, "
      f"n01={pooled['n01']}, n00={pooled['n00']:,}, total {pooled['n_items']:,}.")
    A("")

    # ---- sanity ----------------------------------------------------------
    s = res["sanity"]
    A("## Matcher sanity check")
    A("")
    A(f"Lexical-hit sample n = {s['lexical_hit_sample_n']} "
      f"(RESCORE.md: 126). Semantic agreement with lexical hits: "
      + ", ".join(f"{t} → {s['agreement_by_threshold'][JKEY[t]]}" for t in THRESHOLDS)
      + " (RESCORE.md: 126/126 = 1.0 at every threshold).")
    A("")

    A("## Deviations")
    A("")
    if not deviations:
        A("None. Every per-model cell reproduces RESCORE.md to 3 dp.")
    else:
        A(f"{len(deviations)} of {len(pm) * 12} per-model cells differ from "
          f"RESCORE.md by more than half a unit in the last reported digit.")
        A("")
        A("| model | cell | re-run | RESCORE.md | Δ |")
        A("|---|---|---:|---:|---:|")
        for d in sorted(deviations, key=lambda x: -abs(x[4])):
            A(f"| {d[0]} | {d[1]} | {d[2]:.4f} | {d[3]:.4f} | {d[4]:+.4f} |")
    A("")
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {OUT}")
    print(json.dumps({"n_deviating_cells": len(deviations),
                      "ceilings": ceils, "lexical_ceilings": lex_ceils,
                      "n_negative_ci": f"{n_neg}/{n_tot}",
                      "pooled_n01_0.85": pooled["n01"],
                      "max_single_model_n01": max_n01}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
